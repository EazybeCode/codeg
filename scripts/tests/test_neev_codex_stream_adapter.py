"""Tests for the in-sandbox Codex streaming adapter.

The translation is pinned against the version-matched schema
(`/tmp/neev-codex-0.155.1-schema`, generated by `codex app-server
generate-json-schema`): `item/agentMessage/delta` carries `itemId`/`delta`, and
thread items are camelCase. What the adapter WRITES is the envelope shape the
Rust parser reads, which its own fixtures pin.

The end-to-end tests drive a fake app-server — no credentials, no network, no
sandbox — so they prove the conversation and the exit codes, not the provider.
"""

import json
import os
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

OPERATIONS = Path(__file__).parents[1] / "operations"
sys.path.insert(0, str(OPERATIONS))

import neev_codex_stream_adapter as adapter  # noqa: E402

ADAPTER = str(OPERATIONS / "neev_codex_stream_adapter.py")

# A fake app-server. Answers the handshake, then plays a scripted turn. Its
# behaviour is chosen by FAKE_MODE so one fixture covers success, failure,
# an ignored setting and an unexpected server request.
FAKE = '''#!/usr/bin/env python3
import json, os, sys

MODE = os.environ.get("FAKE_MODE", "ok")

def send(payload):
    sys.stdout.write(json.dumps(payload) + "\\n")
    sys.stdout.flush()

def note(method, params):
    send({"jsonrpc": "2.0", "method": method, "params": params})

if MODE == "silent":
    # Answers nothing at all — the shape of a provider that cannot reach its
    # backend. It must not become a run that produced no output and no reason.
    import time
    time.sleep(30)
    sys.exit(0)

asked = {}
for line in sys.stdin:
    line = line.strip()
    if not line:
        continue
    message = json.loads(line)
    method = message.get("method")
    if method == "initialize":
        send({"jsonrpc": "2.0", "id": message["id"], "result": {
            "userAgent": "fake", "codexHome": "/tmp",
            "platformFamily": "unix", "platformOs": "linux"}})
    elif method == "thread/start":
        # Shaped like ThreadStartResponse in the pinned schema, NOT like the
        # request: the reply reports a sandbox POLICY OBJECT where the request
        # took a mode string, and approvals may come back granular.
        asked = message.get("params") or {}
        result = {
            "thread": {"id": "t1", "cwd": asked.get("cwd"), "cliVersion": "0.155.1",
                       "status": "idle", "turns": [], "ephemeral": True},
            "cwd": asked.get("cwd"),
            "model": asked.get("model") or "gpt-5.1-codex",
            "modelProvider": "openai",
            "sandbox": {"type": "dangerFullAccess"},
            "approvalPolicy": "never",
            "instructionSources": [],
        }
        if asked.get("serviceTier") is not None:
            result["serviceTier"] = asked["serviceTier"]
        if MODE == "mismatch":
            result["model"] = "someone-elses-model"
        if MODE == "granular":
            result["approvalPolicy"] = {"granular": {
                "mcp_elicitations": False, "rules": False, "sandbox_approval": False}}
        if MODE == "codexSandboxed":
            result["sandbox"] = {"type": "workspaceWrite", "writableRoots": []}
        send({"jsonrpc": "2.0", "id": message["id"], "result": result})
    elif method == "turn/start":
        if MODE == "pgid":
            # Report the process group we were started in, so the test can show
            # that one killpg reaches the adapter and the provider together.
            open(os.environ["FAKE_PGID_FILE"], "w").write(str(os.getpgid(0)))
        if MODE == "oversized":
            note("item/agentMessage/delta", {"itemId": "m1", "delta": "x" * (2 * 1024 * 1024)})
            note("turn/completed", {"turn": {"status": "completed"}})
            sys.exit(0)
        if MODE == "serverRequest":
            # A request the adapter cannot serve. It must answer, not wait.
            send({"jsonrpc": "2.0", "id": 900, "method": "item/commandExecution/requestApproval",
                  "params": {"command": "rm -rf /"}})
        note("item/started", {"item": {"type": "commandExecution", "id": "c1",
                                       "command": "ls -la", "status": "inProgress"}})
        note("item/agentMessage/delta", {"itemId": "m1", "delta": "Look"})
        if MODE == "flush":
            # Nothing more until the reader proves it already has the fragment.
            sys.stdin.readline()
        note("item/agentMessage/delta", {"itemId": "m1", "delta": "ing."})
        note("item/completed", {"item": {"type": "reasoning", "id": "r1", "summary": "hidden"}})
        note("item/completed", {"item": {"type": "commandExecution", "id": "c1",
                                         "command": "ls -la", "aggregatedOutput": "a\\nb",
                                         "exitCode": 0, "status": "completed"}})
        note("item/completed", {"item": {"type": "agentMessage", "id": "m1", "text": "Looking."}})
        if MODE == "failed":
            note("turn/completed", {"threadId": "t1", "turn": {
                "id": "u1", "status": "failed",
                "error": {"message": "usage limit reached"}}})
        else:
            note("turn/completed", {"threadId": "t1", "turn": {"id": "u1", "status": "completed"}})
        send({"jsonrpc": "2.0", "id": message["id"], "result": {"turn": {"id": "u1"}}})
        sys.exit(0)
'''


def fake_server(directory):
    path = Path(directory) / "fake_app_server.py"
    path.write_text(FAKE)
    path.chmod(path.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)
    return str(path)


class ArgvTests(unittest.TestCase):
    def parse(self, extra):
        return adapter._parse(["--codex", "/usr/local/bin/codex"] + extra)

    def test_the_prompt_is_taken_literally_including_leading_dashes(self):
        for prompt in ("--help", "-c notify=[]", "  spaced  ", "--"):
            with self.subTest(prompt=prompt):
                self.assertEqual(self.parse(["--", prompt]).prompt, prompt)

    def test_config_overrides_are_global_options_before_the_subcommand(self):
        args = self.parse(["--config", "features.fast_mode=true", "--", "hi"])
        self.assertEqual(
            adapter.codex_argv(args),
            ["/usr/local/bin/codex", "-c", "features.fast_mode=true", "app-server"],
        )

    def test_images_are_local_paths_beside_the_prompt(self):
        self.assertEqual(
            adapter.turn_input("hi", ["/w/run-x/a.png", "/w/run-x/b b.png"]),
            [
                {"type": "text", "text": "hi"},
                {"type": "localImage", "path": "/w/run-x/a.png"},
                {"type": "localImage", "path": "/w/run-x/b b.png"},
            ],
        )

    def test_the_thread_is_started_with_our_sandbox_not_codexs(self):
        args = self.parse(["--model", "m", "--service-tier", "fast", "--", "hi"])
        params = adapter.thread_params(args, "/w/run-x")
        self.assertEqual(params["sandbox"], "danger-full-access")
        self.assertEqual(params["approvalPolicy"], "never")
        self.assertEqual(params["cwd"], "/w/run-x")
        self.assertEqual(params["model"], "m")
        self.assertEqual(params["serviceTier"], "fast")

    def test_the_response_style_is_a_thread_developer_instruction(self):
        """The protocol's own developer channel — not the user's prompt.

        `developerInstructions` is a thread property in the pinned schema,
        separate from `baseInstructions`. We never send the latter: Codex's own
        instructions stay, ours are added alongside them.
        """
        style = 'Lead with the answer.\n\nUse `code` and "quotes" and a \\ one.'
        args = self.parse(["--developer-instructions", style, "--", "hi"])
        params = adapter.thread_params(args, "/w/run-x")
        self.assertEqual(params["developerInstructions"], style)
        self.assertNotIn("baseInstructions", params)
        # The prompt is untouched by it, and carries nothing of it.
        self.assertEqual(args.prompt, "hi")
        self.assertEqual(adapter.turn_input(args.prompt, args.image),
                         [{"type": "text", "text": "hi"}])
        self.assertNotIn("developerInstructions",
                         adapter.start_params(args, "t1", "/w/run-x"))
        # Unset is absent, never an empty string.
        self.assertNotIn(
            "developerInstructions",
            adapter.thread_params(self.parse(["--", "hi"]), "/w/run-x"),
        )

    def test_effort_and_model_reach_the_turn(self):
        args = self.parse(["--model", "m", "--effort", "high", "--", "hi"])
        params = adapter.start_params(args, "t1", "/w/run-x")
        self.assertEqual(params["effort"], "high")
        self.assertEqual(params["model"], "m")
        self.assertEqual(params["threadId"], "t1")
        # An unset choice is absent, never invented as a default.
        unset = adapter.start_params(self.parse(["--", "hi"]), "t1", "/w")
        self.assertNotIn("effort", unset)
        self.assertNotIn("model", unset)


class SettingsTests(unittest.TestCase):
    """The reply is reported in different terms than the request was made in."""

    def test_a_reported_sandbox_policy_is_read_as_the_mode_it_means(self):
        # The request takes `danger-full-access`; the reply reports
        # `{"type": "dangerFullAccess"}`. Comparing those as they stand would
        # refuse every live turn.
        self.assertEqual(
            adapter.sandbox_mode_of({"type": "dangerFullAccess"}), "danger-full-access"
        )
        self.assertEqual(
            adapter.sandbox_mode_of({"type": "workspaceWrite", "writableRoots": []}),
            "workspace-write",
        )
        # A policy this version does not name is not a mismatch.
        for unknown in ({"type": "externalSandbox"}, {}, None, 7):
            self.assertIsNone(adapter.sandbox_mode_of(unknown))

    def test_a_schema_shaped_reply_agrees_with_what_was_asked(self):
        reported = adapter.reported_settings({
            "thread": {"id": "t1"},
            "model": "gpt-5.1-codex",
            "serviceTier": "fast",
            "sandbox": {"type": "dangerFullAccess"},
            "approvalPolicy": "never",
        })
        self.assertEqual(
            adapter.settings_mismatch(
                {"model": "gpt-5.1-codex", "serviceTier": "fast",
                 "sandbox": adapter.SANDBOX_MODE, "approvalPolicy": adapter.APPROVAL_POLICY},
                reported,
            ),
            [],
        )

    def test_granular_approvals_are_carried_as_unreported_not_as_a_mismatch(self):
        reported = adapter.reported_settings({"approvalPolicy": {"granular": {}}})
        self.assertIsNone(reported["approvalPolicy"])

    def test_a_setting_the_thread_changed_is_a_mismatch(self):
        self.assertEqual(
            adapter.settings_mismatch({"model": "a"}, {"model": "b"}), ["model=b"]
        )

    def test_an_unreported_or_unasked_setting_is_not_evidence(self):
        self.assertEqual(adapter.settings_mismatch({"model": "a"}, {}), [])
        self.assertEqual(adapter.settings_mismatch({"model": None}, {"model": "b"}), [])


class TranslateTests(unittest.TestCase):
    def setUp(self):
        self.written = []

        class Recorder(adapter.Emitter):
            def _write(inner, payload):  # noqa: N805 - test double
                self.written.append(payload)

        self.emit = Recorder(None)

    def test_a_delta_is_a_fragment_and_a_completion_is_still_sent(self):
        self.assertIsNone(adapter.translate(
            "item/agentMessage/delta", {"itemId": "m1", "delta": "Look"}, self.emit))
        self.assertIsNone(adapter.translate(
            "item/completed", {"item": {"type": "agentMessage", "id": "m1", "text": "Looking."}},
            self.emit))
        self.assertEqual([entry["type"] for entry in self.written],
                         ["item.delta", "item.completed"])
        # The completion is sent even though the text already streamed: the
        # parser is the one place that dedupes, and it needs this to release
        # the item id it is tracking.
        self.assertEqual(self.written[1]["item"]["text"], "Looking.")

    def test_an_empty_delta_is_not_written_at_all(self):
        adapter.translate("item/agentMessage/delta", {"itemId": "m1", "delta": ""}, self.emit)
        self.assertEqual(self.written, [])

    def test_a_command_is_announced_then_completed_with_its_output(self):
        adapter.translate("item/started", {"item": {
            "type": "commandExecution", "id": "c1", "command": "ls"}}, self.emit)
        adapter.translate("item/completed", {"item": {
            "type": "commandExecution", "id": "c1", "command": "ls",
            "aggregatedOutput": "a\nb", "exitCode": 2}}, self.emit)
        self.assertEqual(self.written[0]["item"]["command"], "ls")
        self.assertEqual(self.written[1]["item"]["aggregated_output"], "a\nb")
        self.assertEqual(self.written[1]["item"]["exit_code"], 2)

    def test_reasoning_is_never_surfaced(self):
        for method, params in (
            ("item/reasoning/textDelta", {"itemId": "r1", "delta": "thinking"}),
            ("item/completed", {"item": {"type": "reasoning", "id": "r1"}}),
        ):
            adapter.translate(method, params, self.emit)
        self.assertEqual(self.written, [])

    def test_a_finished_turn_reports_its_outcome_in_the_exit_code(self):
        self.assertEqual(adapter.translate(
            "turn/completed", {"turn": {"status": "completed"}}, self.emit), 0)
        self.assertEqual(adapter.translate(
            "turn/completed", {"turn": {"status": "failed",
                                        "error": {"message": "usage limit"}}}, self.emit), 4)
        self.assertEqual(self.written[-1], {"type": "turn.failed", "reason": "usage limit"})
        # An interrupted turn is not a completed one either.
        self.assertEqual(adapter.translate(
            "turn/completed", {"turn": {"status": "interrupted"}}, self.emit), 4)


class EndToEndTests(unittest.TestCase):
    """The whole conversation, against a fake app-server."""

    def run_adapter(self, mode, extra=(), stdout=None):
        with tempfile.TemporaryDirectory() as directory:
            environment = dict(os.environ, FAKE_MODE=mode)
            process = subprocess.run(
                [sys.executable, ADAPTER, "--codex", fake_server(directory),
                 "--cwd", directory, *extra, "--", "hi"],
                capture_output=True, text=True, timeout=30, env=environment,
            )
            lines = [json.loads(line) for line in process.stdout.splitlines() if line.strip()]
            return process.returncode, lines

    def test_a_turn_streams_then_completes(self):
        code, lines = self.run_adapter("ok")
        self.assertEqual(code, 0)
        self.assertEqual(
            [entry["type"] for entry in lines],
            ["item.started", "item.delta", "item.delta",
             "item.completed", "item.completed", "turn.completed"],
        )
        # The reply arrived as fragments AND as the completion the parser
        # dedupes against.
        self.assertEqual([entry["item"]["delta"] for entry in lines
                          if entry["type"] == "item.delta"], ["Look", "ing."])
        self.assertEqual(lines[0]["item"]["command"], "ls -la")

    def test_a_failed_turn_exits_nonzero_so_a_partial_reply_is_not_a_success(self):
        code, lines = self.run_adapter("failed")
        self.assertEqual(code, 4)
        self.assertEqual(lines[-1], {"type": "turn.failed", "reason": "usage limit reached"})

    def test_a_setting_the_provider_ignored_stops_the_turn_before_it_runs(self):
        code, lines = self.run_adapter("mismatch", extra=["--model", "gpt-5.1-codex"])
        self.assertEqual(code, 4)
        self.assertEqual(len(lines), 1)
        self.assertEqual(lines[0]["type"], "turn.failed")
        self.assertIn("someone-elses-model", lines[0]["reason"])

    def test_a_schema_shaped_reply_does_not_refuse_the_turn(self):
        # The regression this guards: the reply reports a sandbox POLICY OBJECT
        # where the request took a mode STRING. Read naively, every live turn
        # would be refused before it ran.
        code, lines = self.run_adapter(
            "ok", extra=["--model", "gpt-5.1-codex", "--service-tier", "fast"]
        )
        self.assertEqual(code, 0)
        self.assertEqual(lines[-1]["type"], "turn.completed")

    def test_granular_approvals_do_not_refuse_the_turn(self):
        code, lines = self.run_adapter("granular")
        self.assertEqual(code, 0)
        self.assertEqual(lines[-1]["type"], "turn.completed")

    def test_a_thread_that_kept_codexs_own_sandbox_is_refused(self):
        # Inside our namespaces Codex cannot build a sandbox of its own, so
        # every command it ran would fail. Better to say so than to stream a
        # turn whose tools cannot work.
        code, lines = self.run_adapter("codexSandboxed")
        self.assertEqual(code, 4)
        self.assertIn("sandbox=workspace-write", lines[0]["reason"])

    def test_an_unexpected_server_request_is_refused_and_the_turn_goes_on(self):
        code, lines = self.run_adapter("serverRequest")
        self.assertEqual(code, 0)
        self.assertEqual(lines[-1]["type"], "turn.completed")

    def test_a_provider_that_never_starts_says_so(self):
        code, lines = self.run_adapter("ok", extra=[])
        self.assertEqual(code, 0)  # sanity: the fixture itself runs
        process = subprocess.run(
            [sys.executable, ADAPTER, "--codex", "/nonexistent/codex", "--", "hi"],
            capture_output=True, text=True, timeout=30,
        )
        self.assertEqual(process.returncode, 3)
        self.assertEqual(json.loads(process.stdout)["type"], "turn.failed")

    def test_an_empty_prompt_never_reaches_the_provider(self):
        process = subprocess.run(
            [sys.executable, ADAPTER, "--codex", "/nonexistent/codex", "--", ""],
            capture_output=True, text=True, timeout=30,
        )
        self.assertEqual(process.returncode, 2)

    def test_an_oversized_provider_message_ends_the_turn_rather_than_being_read(self):
        # Bounded BEFORE the allocation: a message larger than the cap is not
        # half-read and not accumulated, and one is enough to distrust the rest.
        code, lines = self.run_adapter("oversized")
        self.assertEqual(code, 4)
        self.assertEqual(lines[-1], {"type": "turn.failed", "reason": "oversized provider message"})
        self.assertTrue(all(len(json.dumps(line)) < adapter.MAX_LINE_BYTES for line in lines))

    def test_the_provider_stays_in_the_process_group_that_cancels_the_turn(self):
        # Cancellation is one `killpg` from the launcher. If the adapter started
        # a session of its own, that signal would stop the adapter and leave the
        # app-server running with the reader's credentials.
        with tempfile.TemporaryDirectory() as directory:
            pgid_file = os.path.join(directory, "pgid")
            environment = dict(os.environ, FAKE_MODE="pgid", FAKE_PGID_FILE=pgid_file)
            process = subprocess.run(
                [sys.executable, ADAPTER, "--codex", fake_server(directory),
                 "--cwd", directory, "--", "hi"],
                capture_output=True, text=True, timeout=30, env=environment,
            )
            self.assertEqual(process.returncode, 0)
            self.assertEqual(
                Path(pgid_file).read_text().strip(),
                str(os.getpgid(0)),
                "the app-server must share the group the launcher signals",
            )

    def test_the_provider_is_reaped_when_the_adapter_returns(self):
        # A killed child that is never waited for stays a zombie in the pid
        # namespace the launcher is about to tear down.
        with tempfile.TemporaryDirectory() as directory:
            environment = dict(os.environ, FAKE_MODE="ok")
            process = subprocess.run(
                [sys.executable, ADAPTER, "--codex", fake_server(directory),
                 "--cwd", directory, "--", "hi"],
                capture_output=True, text=True, timeout=30, env=environment,
            )
            self.assertEqual(process.returncode, 0)
            # The adapter exited, so everything it started has been waited for;
            # a leaked child would keep this pipe open past the run.
            self.assertEqual(process.stderr, "")

    def test_a_fragment_is_readable_before_the_turn_ends(self):
        # The whole point: a delta held in a buffer until the turn finishes is
        # not a delta. The fake waits for a byte before sending anything more,
        # so reading the first fragment here proves it was flushed.
        with tempfile.TemporaryDirectory() as directory:
            environment = dict(os.environ, FAKE_MODE="flush")
            process = subprocess.Popen(
                [sys.executable, ADAPTER, "--codex", fake_server(directory),
                 "--cwd", directory, "--", "hi"],
                stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, env=environment,
            )
            try:
                first = json.loads(process.stdout.readline())
                second = json.loads(process.stdout.readline())
                self.assertEqual(first["type"], "item.started")
                self.assertEqual(second["item"]["delta"], "Look")
            finally:
                process.kill()
                process.wait(timeout=10)
                process.stdout.close()

    def test_a_provider_that_answers_nothing_says_so_rather_than_hanging(self):
        # A silent provider (no network, no credentials) previously produced no
        # output and no reason, which reads as a run that simply did nothing.
        with tempfile.TemporaryDirectory() as directory:
            environment = dict(os.environ, FAKE_MODE="silent")
            process = subprocess.run(
                [sys.executable, "-c",
                 f"import neev_codex_stream_adapter as a, sys;"
                 f"a.HANDSHAKE_TIMEOUT_SECS=1;"
                 f"sys.exit(a.main(['--codex', {fake_server(directory)!r},"
                 f"'--cwd', {directory!r}, '--', 'hi']))"],
                capture_output=True, text=True, timeout=30, env=environment,
                cwd=str(OPERATIONS),
            )
            self.assertEqual(process.returncode, 4)
            self.assertEqual(
                json.loads(process.stdout)["reason"], "provider did not start the turn"
            )


